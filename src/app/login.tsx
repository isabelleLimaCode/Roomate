import React, { useState } from 'react';
import {
  StyleSheet,
  Text,
  View,
  TextInput,
  TouchableOpacity,
  ActivityIndicator,
  KeyboardAvoidingView,
  Platform,
  Alert,
} from 'react-native';
import { Ionicons } from '@expo/vector-icons';
import { useRouter } from 'expo-router';
import { supabase } from '../database/supabase';

export default function LoginScreen() {
  const router = useRouter();
  const [email, setEmail] = useState('');
  const [password, setPassword] = useState('');
  const [loading, setLoading] = useState(false);
  const [showPassword, setShowPassword] = useState(false);

  async function handleLogin() {
  if (!email || !password) {
    Alert.alert('Atenção', 'Por favor, preenche todos os campos.');
    return;
  }

  try {
    setLoading(true);

    const { error } = await supabase.auth.signInWithPassword({
      email: email.trim(),
      password,
    });

    if (error) {
      Alert.alert('Erro no Login', error.message);
    } else {
      setEmail('');
      setPassword('');
      router.replace('/');
    }
  } catch (err) {
    Alert.alert('Erro', 'Ocorreu um erro inesperado.');
  } finally {
    setLoading(false); 
  }
}



  return (
    <KeyboardAvoidingView
      behavior={Platform.OS === 'ios' ? 'padding' : 'height'}
      style={styles.container}
    >
      <View style={styles.headerContainer}>
        <View style={styles.iconCircle}>
          <Ionicons name="home" size={40} color="#6366f1" />
        </View>
        <Text style={styles.title}>Roommate</Text>
        <Text style={styles.subtitle}>Gerencia a tua casa sem complicações</Text>
      </View>

      <View style={styles.formContainer}>
        {/* Campo de Email */}
        <View style={styles.inputContainer}>
          <Ionicons name="mail-outline" size={20} color="#94a3b8" style={styles.inputIcon} />
          <TextInput
            style={styles.input}
            placeholder="Email"
            placeholderTextColor="#94a3b8"
            keyboardType="email-address"
            autoCapitalize="none"
            value={email}
            onChangeText={setEmail}
          />
        </View>

        {/* Campo de Password */}
        <View style={styles.inputContainer}>
          <Ionicons name="lock-closed-outline" size={20} color="#94a3b8" style={styles.inputIcon} />
          <TextInput
            style={styles.input}
            placeholder="Palavra-passe"
            placeholderTextColor="#94a3b8"
            secureTextEntry={!showPassword}
            value={password}
            onChangeText={setPassword}
          />
          <TouchableOpacity onPress={() => setShowPassword(!showPassword)}>
            <Ionicons
              name={showPassword ? 'eye-off-outline' : 'eye-outline'}
              size={20}
              color="#94a3b8"
            />
          </TouchableOpacity>
        </View>

        {/* Botão de Entrar */}
        <TouchableOpacity
          style={[styles.button, loading && styles.buttonDisabled]}
          onPress={handleLogin}
          disabled={loading}
        >
          {loading ? (
            <ActivityIndicator color="#fff" />
          ) : (
            <>
              <Text style={styles.buttonText}>Entrar</Text>
              <Ionicons name="arrow-forward" size={20} color="#fff" style={styles.buttonIcon} />
            </>
          )}
        </TouchableOpacity>

        {/* Botão Secundário para Criar Conta */}
        <TouchableOpacity
          style={styles.secondaryButton}

          onPress={() => {
            console.log('Navegando para a página de registo...');
            router.push('/signup');
          }}
        >
          <Text style={styles.secondaryButtonText}>Ainda não tens conta? Criar Conta</Text>
        </TouchableOpacity>
      </View>
    </KeyboardAvoidingView>
  );
}

